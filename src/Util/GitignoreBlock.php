namespace CitOmni\Installer\Util;

use CitOmni\Installer\Exception\ConflictException;
use CitOmni\Installer\Exception\InstallerException;

/**
 * Pure helpers for the installer-owned block in an application's .gitignore.
 *
 * The block is delimited by two marker lines and generated from the installed package
 * manifests. Every byte outside the markers belongs to the application and is preserved.
 *
 * Behavior:
 * - body() builds the canonical block body in three groups: package ignore rules,
 *   package exceptions, then the anchored package-managed targets.
 *   1) Each group is sorted bytewise and deduplicated, so the block does not depend on
 *      package discovery order.
 *   2) Order inside a group is irrelevant: ignore rules and targets only ignore, and
 *      exceptions only re-include. Git uses the last matching line, so exceptions win
 *      over every ignore rule, and managed targets stay ignored even if an exception
 *      names them.
 * - apply() replaces an existing block in place. Without one, it inserts the block after
 *   any marker blocks of other tools at the top of the file, followed by a blank line, so
 *   application rules below it keep the final say.
 * - An empty body removes an existing block and leaves a file without one untouched.
 * - remove() drops the block plus the blank separator line apply() inserted after it,
 *   which restores the bytes that existed before the insertion. The only exception is
 *   a line ending apply() had to add to an unterminated marker block above it.
 * - The file's line ending (CRLF when present, otherwise LF) and a leading UTF-8 BOM
 *   are preserved.
 *
 * Notes:
 * - Pure utility: no IO, no App. Callers read and write the file.
 * - Marker lines are recognized after trimming trailing spaces and tabs. A missing,
 *   repeated or misordered marker, or any other line that starts like one, throws
 *   ConflictException because the installer can no longer tell which bytes it owns.
 *
 * Typical usage:
 *   $body = GitignoreBlock::body($ignore, $exceptions, $targets);
 *   $bytes = GitignoreBlock::apply($bytes, $body);
 */
final class GitignoreBlock {

	/** App-relative file that carries the block. */
	public const FILE = '.gitignore';

	/** First line of the installer-owned block. */
	public const BEGIN = '###> citomni/installer ###';

	/** Last line of the installer-owned block. */
	public const END = '###< citomni/installer ###';

	/** UTF-8 byte order mark, kept in front of the file when present. */
	private const BOM = "\xEF\xBB\xBF";

	/** Comment lines opening every non-empty block. */
	private const HEADER = [
		'# Generated by citomni/installer from the installed package manifests.',
		'# Rewritten by install, sync and migrate; edits inside this block are lost.',
		'# Application rules belong after the block.',
	];

	/**
	 * Not instantiable: pure static utility.
	 */
	private function __construct() {
	}


	// ----------------------------------------------------------------
	// Block content
	// ----------------------------------------------------------------

	/**
	 * Build the canonical block body (without marker lines).
	 *
	 * @param  array<int,string> $ignore      Validated package ignore rules.
	 * @param  array<int,string> $exceptions  Validated package exceptions, including the leading "!".
	 * @param  array<int,string> $targets     App-relative managed targets (manifest form).
	 * @return list<string>                   Body lines, or an empty list when nothing is ignored.
	 */
	public static function body(array $ignore, array $exceptions, array $targets): array {
		$groups = [
			'# Package runtime paths' => self::canonical($ignore),
			'# Package runtime files kept in Git' => self::canonical($exceptions),
			'# Package-managed scaffold targets' => self::canonical(\array_map(self::literal(...), $targets)),
		];

		$body = [];
		foreach ($groups as $heading => $lines) {
			if ($lines === []) {
				continue;
			}
			$body[] = '';
			$body[] = $heading;
			\array_push($body, ...$lines);
		}

		return $body === [] ? [] : [...self::HEADER, ...$body];
	}


	/**
	 * Express an app-relative path as an anchored pattern that matches only that path.
	 *
	 * Behavior:
	 * - Prefixes "/" so the pattern is anchored at the application root.
	 * - Escapes the wildcard characters "*", "?" and "[" plus any backslash.
	 * - Escapes trailing spaces, which Git would otherwise trim.
	 *
	 * @param  string $target  Normalized app-relative path, e.g. "public/index.php".
	 * @return string          Pattern, e.g. "/public/index.php".
	 * @throws InstallerException  When the path contains a control character.
	 */
	public static function literal(string $target): string {
		if (\preg_match('/[\x00-\x1F\x7F]/', $target) === 1) {
			throw new InstallerException('A .gitignore literal cannot contain control characters: ' . \var_export($target, true));
		}

		$escaped = (string)\preg_replace('/[\\\\*?\[]/', '\\\\$0', $target);
		$trimmed = \rtrim($escaped, ' ');

		return '/' . $trimmed . \str_repeat('\\ ', \strlen($escaped) - \strlen($trimmed));
	}


	// ----------------------------------------------------------------
	// File transformations
	// ----------------------------------------------------------------

	/**
	 * Return the body lines of the current block.
	 *
	 * @param  string $bytes  Current .gitignore bytes.
	 * @return list<string>|null  Body lines without line endings, or null when no block exists.
	 * @throws ConflictException  When the markers are malformed.
	 */
	public static function extract(string $bytes): ?array {
		[, $text] = self::splitBom($bytes);
		$lines = self::lines($text);
		$span = self::locate($lines);
		if ($span === null) {
			return null;
		}

		$body = [];
		for ($index = $span[0] + 1; $index < $span[1]; $index++) {
			$body[] = $lines[$index][1];
		}

		return $body;
	}


	/**
	 * Return the file bytes with the block set to the given body.
	 *
	 * @param  string       $bytes  Current .gitignore bytes.
	 * @param  list<string> $body   Desired body from body(); empty removes the block.
	 * @return string               Updated bytes; identical bytes mean nothing to do.
	 * @throws ConflictException    When the markers are malformed.
	 */
	public static function apply(string $bytes, array $body): string {
		[$bom, $text] = self::splitBom($bytes);
		$lines = self::lines($text);
		$span = self::locate($lines);
		$eol = \str_contains($text, "\r\n") ? "\r\n" : "\n";
		$block = $body === [] ? '' : self::BEGIN . $eol . \implode($eol, $body) . $eol . self::END . $eol;

		if ($span !== null) {
			$start = $lines[$span[0]][0];
			$end = $lines[$span[1]][2];
			if ($block === '') {
				return $bom . self::cut($text, $start, $end);
			}
			return $bom . \substr($text, 0, $start) . $block . \substr($text, $end);
		}

		if ($block === '') {
			return $bytes;
		}

		$at = self::insertionOffset($lines, \strlen($text));
		$before = \substr($text, 0, $at);
		$after = \substr($text, $at);
		if ($before !== '' && !\str_ends_with($before, "\n")) {
			// The preceding marker block ends the file without a line ending.
			$before .= $eol;
		}

		return $bom . $before . $block . ($after === '' ? '' : $eol) . $after;
	}


	/**
	 * Return the file bytes without the block and its insertion separator.
	 *
	 * @param  string $bytes  Current .gitignore bytes.
	 * @return string         Bytes without the installer block.
	 * @throws ConflictException  When the markers are malformed.
	 */
	public static function remove(string $bytes): string {
		[$bom, $text] = self::splitBom($bytes);
		$lines = self::lines($text);
		$span = self::locate($lines);
		if ($span === null) {
			return $bytes;
		}

		return $bom . self::cut($text, $lines[$span[0]][0], $lines[$span[1]][2]);
	}


	// ----------------------------------------------------------------
	// Internals
	// ----------------------------------------------------------------

	/**
	 * Sort and deduplicate one group bytewise.
	 *
	 * @param  array<int,string> $lines
	 * @return list<string>
	 */
	private static function canonical(array $lines): array {
		$lines = \array_values(\array_unique($lines, \SORT_STRING));
		\sort($lines, \SORT_STRING);
		return $lines;
	}


	/**
	 * Split off a leading UTF-8 BOM.
	 *
	 * @return array{0:string,1:string}  [BOM or '', remaining bytes].
	 */
	private static function splitBom(string $bytes): array {
		return \str_starts_with($bytes, self::BOM)
			? [self::BOM, \substr($bytes, \strlen(self::BOM))]
			: ['', $bytes];
	}


	/**
	 * Split text into lines with their byte offsets.
	 *
	 * @return list<array{0:int,1:string,2:int}>  [start offset, content without line ending, end offset].
	 */
	private static function lines(string $text): array {
		$lines = [];
		$offset = 0;
		$length = \strlen($text);

		while ($offset < $length) {
			$newline = \strpos($text, "\n", $offset);
			$contentEnd = $newline === false ? $length : $newline;
			$content = \substr($text, $offset, $contentEnd - $offset);
			if (\str_ends_with($content, "\r")) {
				$content = \substr($content, 0, -1);
			}
			$end = $newline === false ? $length : $newline + 1;
			$lines[] = [$offset, $content, $end];
			$offset = $end;
		}

		return $lines;
	}


	/**
	 * Find the begin and end marker lines of the installer block.
	 *
	 * Trailing spaces and tabs after a marker are tolerated; apply() rewrites the marker
	 * lines exactly. Any other line that starts like a marker is malformed.
	 *
	 * @param  list<array{0:int,1:string,2:int}> $lines
	 * @return array{0:int,1:int}|null  Line indexes of the markers, or null without a block.
	 * @throws ConflictException  When a marker is missing, repeated, out of order or garbled.
	 */
	private static function locate(array $lines): ?array {
		$begin = [];
		$end = [];
		$garbled = false;
		foreach ($lines as $index => $line) {
			$content = \rtrim($line[1], " \t");
			if ($content === self::BEGIN) {
				$begin[] = $index;
			} elseif ($content === self::END) {
				$end[] = $index;
			} elseif (\preg_match('~^###[<>] citomni/installer(?:\s|$)~', $content) === 1) {
				$garbled = true;
			}
		}

		if (!$garbled && $begin === [] && $end === []) {
			return null;
		}
		if ($garbled || \count($begin) !== 1 || \count($end) !== 1 || $begin[0] > $end[0]) {
			throw new ConflictException(\sprintf(
				'The citomni/installer block in %s is malformed: expected exactly one "%s" line followed by one "%s" line. Repair or remove the markers and rerun the command.',
				self::FILE,
				self::BEGIN,
				self::END
			));
		}

		return [$begin[0], $end[0]];
	}


	/**
	 * Byte offset where a new block is inserted.
	 *
	 * Skips complete "###> name ###" ... "###< name ###" blocks of other tools at the
	 * top of the file, plus one blank line after the last of them.
	 *
	 * @param  list<array{0:int,1:string,2:int}> $lines
	 * @param  int $length  Text length in bytes.
	 * @return int
	 */
	private static function insertionOffset(array $lines, int $length): int {
		$count = \count($lines);
		$next = 0;
		$found = false;

		while (true) {
			$probe = $next;
			while ($probe < $count && $lines[$probe][1] === '') {
				$probe++;
			}
			if ($probe >= $count || \preg_match('/^###> (\S+) ###$/', $lines[$probe][1], $match) !== 1) {
				break;
			}

			$close = null;
			for ($index = $probe + 1; $index < $count; $index++) {
				if ($lines[$index][1] === '###< ' . $match[1] . ' ###') {
					$close = $index;
					break;
				}
			}
			if ($close === null) {
				break;
			}

			$next = $close + 1;
			$found = true;
		}

		if (!$found) {
			return 0;
		}
		if ($next < $count && $lines[$next][1] === '') {
			$next++;
		}

		return $next < $count ? $lines[$next][0] : $length;
	}


	/**
	 * Remove a byte range plus one directly following blank line.
	 */
	private static function cut(string $text, int $start, int $end): string {
		$after = \substr($text, $end);
		if (\str_starts_with($after, "\r\n")) {
			$after = \substr($after, 2);
		} elseif (\str_starts_with($after, "\n")) {
			$after = \substr($after, 1);
		}

		return \substr($text, 0, $start) . $after;
	}
}
